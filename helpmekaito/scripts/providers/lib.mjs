// Shared by every task provider: the cache file format, the index, the local lock, option parsing.
// A provider is a default export: { remote, indexDone, isDone(t), where(t), redact?(s), commands{}, op(op, args) }.
import { readFileSync, writeFileSync, mkdirSync, renameSync, rmdirSync, readdirSync, statSync, existsSync, copyFileSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';
import { randomBytes } from 'node:crypto';

export const { M, D, B, S, MGR } = process.env;
export const ctx = { P: null };  // the active provider, set by kaito-tasks.mjs
export const die = (m) => { console.error(`kaito-tasks: ${m}`); process.exit(1); };
export const one = (s) => String(s ?? '').replace(/[\r\n]+/g, ' ').trim();
const q = (v) => JSON.stringify(one(v));  // every frontmatter value is a quoted string; JSON escapes are valid YAML
export const fm = (o) => '---\n' + Object.entries(o).map(([k, v]) => `${k}: ${q(v)}`).join('\n') + '\n---\n';
export const parse = (text) => {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/), meta = {};
  if (m) for (const l of m[1].split('\n')) {
    const x = l.match(/^(\w+): (.*)$/);
    if (x) { try { meta[x[1]] = JSON.parse(x[2]); } catch { meta[x[1]] = x[2]; } }
  }
  return { meta, body: m ? text.slice(m[0].length) : text };
};
export const slug = (t) => String(t).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+/, '').slice(0, 50).replace(/-+$/, '') || 'task';
export const inside = (dir, f) => {
  const p = resolve(dir, f);
  if (!p.startsWith(resolve(dir) + sep)) die('refusing a path outside the tasks folder');
  return p;
};
export const atomic = (file, text) => { const t = `${file}.${process.pid}.tmp`; writeFileSync(t, text); renameSync(t, file); };
export const rnd = (n) => [...randomBytes(n)].map((b) => 'abcdefghijklmnopqrstuvwxyz0123456789'[b % 36]).join('');
export const openItems = (body) => (body.match(/^- \[ \] .*<!-- id:\S+ -->$/gm) || []).length;
export const taskFiles = (dir = D) => existsSync(dir)
  ? readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'index.md').map((f) => ({ f, path: join(dir, f), ...parse(readFileSync(join(dir, f), 'utf8')) }))
  : [];
export function writeIndex(dir = D) {
  const P = ctx.P;
  mkdirSync(dir, { recursive: true });
  const rows = taskFiles(dir).filter((t) => P.indexDone || !P.isDone(t))
    .map((t) => `- [[${t.f.slice(0, -3)}]] ${P.where(t)} · ${one(t.meta.title)} (${openItems(t.body)} open)`);
  atomic(join(dir, 'index.md'), `<!-- generated by kaito-tasks.sh; edit tasks through helpmekaito -->\n# Tasks\n\n${rows.join('\n')}\n`);
}

// Lock around local writes only. ponytail: a lock a killed run left is taken over after 5s.
let held = '';
process.on('exit', () => { if (held) try { rmdirSync(held); } catch {} });
export function locked(fn) {
  const L = join(M, 'tasks', `.${S}.lock`);
  mkdirSync(join(M, 'tasks'), { recursive: true });
  for (let i = 0; ; i++) {
    try { mkdirSync(L); break; } catch (e) {
      if (e.code !== 'EEXIST') throw e;
      if (i === 50) try { rmdirSync(L); } catch {}
      if (i > 51) die('tasks folder is busy, try again');
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
    }
  }
  held = L;
  try { return fn(); } finally { rmdirSync(L); held = ''; }
}

// A cache file edited after its sync keeps the edit as a conflict copy.
export function keepEdit(t, cdir) {
  const synced = Date.parse(t.meta.synced_at);
  if (!synced || Math.floor(statSync(t.path).mtimeMs / 1000) <= Math.floor(synced / 1000)) return;
  mkdirSync(cdir, { recursive: true });
  const name = `${t.f.slice(0, -3)}.conflict.md`;
  copyFileSync(t.path, join(cdir, name));
  console.error(`warning: ${t.f} was edited locally; your copy is in conflicts/${name}. Edit tasks through helpmekaito.`);
}

export const itemId = (x) => (/^[A-Za-z0-9-]+$/.test(x || '') ? x : die(`bad item id ${x ?? ''}`));
export function opts(rest) {
  const o = {};
  for (let i = 0; i < rest.length; i += 2) {
    const k = rest[i].replace(/^--/, '');
    if (!['list', 'due', 'desc'].includes(k) || rest[i + 1] === undefined) die(`unknown option ${rest[i]}`);
    o[k] = rest[i + 1];
  }
  if (o.due && Number.isNaN(Date.parse(o.due))) die(`bad due date ${o.due}`);
  return o;
}
